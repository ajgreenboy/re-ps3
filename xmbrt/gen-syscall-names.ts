// Generates syscall_names.inc (index -> name) from RPCS3's positional g_ppu_syscall_table,
// so xmbrt logs syscalls under the same names RPCS3 uses.
// usage: bun gen-syscall-names.ts <rpcs3>/rpcs3/Emu/Cell/lv2/lv2.cpp <out.inc>
const [src, out] = process.argv.slice(2);
if (!src || !out) throw new Error("usage: bun gen-syscall-names.ts <lv2.cpp> <out.inc>");

const text = (await Bun.file(src).text()).replaceAll("\r", "");
const start = text.indexOf("g_ppu_syscall_table");
const open = text.indexOf("{", start);
const close = text.indexOf("\n};", open);
const body = text.slice(open + 1, close);

const names: string[] = [];
const isNull: boolean[] = []; // null_func / NULL_FUNC(x): RPCS3 returns CELL_OK without doing anything
let mismatches = 0;
for (const rawLine of body.split("\n")) {
  const comment = rawLine.match(/\/\/\s*(\d+)/);
  const line = rawLine.replace(/\/\/.*$/, "");
  const firstIndex = names.length;
  for (const tok of line.split(",").map((t) => t.trim()).filter(Boolean)) {
    const named = tok.match(/^(BIND_SYSC|NULL_FUNC)\((\w+)\)$/);
    if (named) {
      names.push(named[2]);
      isNull.push(named[1] === "NULL_FUNC");
    } else if (tok === "uns_func" || tok === "null_func") {
      names.push("");
      isNull.push(tok === "null_func");
    } else throw new Error(`unrecognised table entry: ${tok}`);
  }
  // Single-entry lines carry their index ("//12  (0x00C)"); use them to check the count.
  if (comment && names.length === firstIndex + 1 && Number(comment[1]) !== firstIndex) {
    console.error(`index mismatch: ${names[firstIndex]} at ${firstIndex}, comment says ${comment[1]}`);
    mismatches++;
  }
}
if (mismatches) process.exit(1);

const lines = names.map((n, i) => (n ? `\t/* ${i} */ "${n}",` : `\t/* ${i} */ nullptr,`));
await Bun.write(
  out,
  `// Generated by gen-syscall-names.ts from RPCS3 lv2.cpp. Do not edit.\n` +
    `static const char* const kSyscallNames[${names.length}] = {\n${lines.join("\n")}\n};\n\n` +
    `// RPCS3 null_func entries (unimplemented there, return CELL_OK)\n` +
    `static const bool kSyscallNullOk[${names.length}] = {\n${isNull.map((b) => (b ? "1" : "0")).join(",")}\n};\n`,
);
console.log(`${names.length} entries, ${names.filter(Boolean).length} named -> ${out}`);
