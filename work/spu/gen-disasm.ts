// Generates spu-disasm.generated.ts from RPCS3's SPU tables (local source, not copied into the repo):
//   rpcs3/Emu/Cell/SPUOpcodes.h  - opcode table: { magn, value, GET(NAME) } covers indices (value << magn) .. +2^magn-1
//                                  of the instruction's top 11 bits
//   rpcs3/Emu/Cell/SPUDisAsm.h   - per-instruction operand formatting, DisAsm("mnemonic", operands...)
// Usage: bun gen-disasm.ts <rpcs3 source root> <out.ts>
import { readFileSync, writeFileSync } from "node:fs";
const [root, out] = process.argv.slice(2);
const opcodes = readFileSync(`${root}/rpcs3/Emu/Cell/SPUOpcodes.h`, "utf8");
const disasm = readFileSync(`${root}/rpcs3/Emu/Cell/SPUDisAsm.h`, "utf8");

const table: { magn: number; value: number; name: string }[] = [];
for (const m of opcodes.matchAll(/\{ (\d+), (0x[0-9a-f]+), GET\(([A-Z0-9_]+)\) \}/g))
  table.push({ magn: +m[1], value: parseInt(m[2], 16), name: m[3] });

// Operand expressions of each inline DisAsm call, translated to TypeScript over the decoded fields `f` and `pc`.
const formats: Record<string, string> = {};
for (const m of disasm.matchAll(/void ([A-Z0-9_]+)\(spu_opcode_t op\)\s*\{\s*DisAsm\(([^;]*)\);\s*\}/g)) {
  let args = m[2]
    .replace(/spu_reg_name\[op\.(\w+)\]/g, (_, r) => `reg(f.${r})`)
    .replace(/spu_spreg_name\[op\.(\w+)\]/g, (_, r) => `"spr" + f.${r}`)
    .replace(/spu_ch_name\[op\.(\w+)\]/g, (_, r) => `"ch" + f.${r}`)
    .replace(/DisAsmBranchTarget\(/g, "target(")
    .replace(/dump_pc/g, "pc")
    .replace(/static_cast<u8>\(([^)]*)\)/g, "(($1) & 0xff)")
    .replace(/static_cast<u16>\(([^)]*)\)/g, "(($1) & 0xffff)")
    .replace(/op\./g, "f.");
  formats[m[1]] = args;
}
// Instructions whose formatting lives in SPUDisAsm.cpp: plain register forms are enough here.
const fallback: Record<string, string> = {
  WRCH: `"wrch", "ch" + f.ra, reg(f.rt)`, RDCH: `"rdch", reg(f.rt), "ch" + f.ra`, RCHCNT: `"rchcnt", reg(f.rt), "ch" + f.ra`,
  SHUFB: `"shufb", reg(f.rt4), reg(f.ra), reg(f.rb), reg(f.rc)`,
  BI: `"bi", reg(f.ra)`, BISL: `"bisl", reg(f.rt), reg(f.ra)`, BIZ: `"biz", reg(f.rt), reg(f.ra)`, BINZ: `"binz", reg(f.rt), reg(f.ra)`,
  BIHZ: `"bihz", reg(f.rt), reg(f.ra)`, BIHNZ: `"bihnz", reg(f.rt), reg(f.ra)`, IRET: `"iret", reg(f.ra)`, BISLED: `"bisled", reg(f.rt), reg(f.ra)`,
  STOP: `"stop", hex(f.raw & 0x3fff)`, STOPD: `"stopd"`, LNOP: `"lnop"`, NOP: `"nop"`, SYNC: `"sync"`, DSYNC: `"dsync"`,
  HBRA: `"hbra", hex(target(((f.r0h << 7) | f.rt))), hex(f.i16 << 2)`,
  HBRR: `"hbrr", hex(target(((f.r0h << 7) | f.rt))), hex(target(f.si16))`,
  // multi-line bodies in SPUDisAsm.h (extra comments / made-up mnemonics)
  SHLQBYI: `f.si7 ? "shlqbyi" : "mr", reg(f.rt), reg(f.ra), ...(f.si7 ? [f.si7] : [])`,
  BR: `"br", hex(target(f.si16))`,
  ILHU: `"ilhu", reg(f.rt), hex(f.i16), "; =" + hex(f.i16 << 16)`,
  ILH: `"ilh", reg(f.rt), hex(f.i16)`,
  IOHL: `"iohl", reg(f.rt), hex(f.i16)`,
  ORI: `f.si10 ? "ori" : "mr", reg(f.rt), reg(f.ra), ...(f.si10 ? [f.si10] : [])`,
  AI: `"ai", reg(f.rt), reg(f.ra), f.si10`,
  XORI: `"xori", reg(f.rt), reg(f.ra), f.si10`,
};
const missing: string[] = [];
let code = `// Generated by gen-disasm.ts from RPCS3's SPUOpcodes.h / SPUDisAsm.h. Do not edit.\n`;
code += `export interface Fields { raw: number; rt: number; rc: number; ra: number; rb: number; rt4: number; e: number; d: number; c: number;\n`;
code += `  r0h: number; roh: number; i7: number; si7: number; i8: number; si10: number; i16: number; si16: number; i18: number; }\n`;
code += `const bits = (v: number, s: number, n: number) => (v >>> s) & ((1 << n) - 1);\n`;
code += `const sbits = (v: number, s: number, n: number) => { const x = bits(v, s, n); return x & (1 << (n - 1)) ? x - (1 << n) : x; };\n`;
code += `export function fields(raw: number): Fields { return { raw, rt: bits(raw,0,7), rc: bits(raw,0,7), ra: bits(raw,7,7), rb: bits(raw,14,7), rt4: bits(raw,21,7),\n`;
code += `  e: bits(raw,18,1), d: bits(raw,19,1), c: bits(raw,20,1), r0h: sbits(raw,23,2), roh: sbits(raw,14,2), i7: bits(raw,14,7), si7: sbits(raw,14,7),\n`;
code += `  i8: bits(raw,14,8), si10: sbits(raw,14,10), i16: bits(raw,7,16), si16: sbits(raw,7,16), i18: bits(raw,7,18) }; }\n`;
code += `export const names: string[] = new Array(2048).fill("UNK");\n`;
for (const t of table) for (let i = 0; i < 1 << t.magn; ++i) code += "";
code += `const table: [number, number, string][] = ${JSON.stringify(table.map(t => [t.magn, t.value, t.name]))};\n`;
code += `for (const [m, v, n] of table) for (let i = 0; i < 1 << m; ++i) names[(v << m) + i] = n;\n`;
code += `export function decode(raw: number): string { return names[raw >>> 21]; }\n`;
code += `export function disassemble(raw: number, pc: number): { name: string; text: string; target?: number } {\n`;
code += `  const f = fields(raw), name = decode(raw); let target_: number | undefined;\n`;
code += `  const target = (imm: number) => (target_ = (pc + (imm << 2)) & 0x3fffc);\n`;
code += `  const reg = (r: number) => "$" + r; const hex = (v: number) => "0x" + (v >>> 0).toString(16);\n`;
code += `  const fmt = (m: string, ...a: unknown[]) => ({ name, text: m + (a.length ? " " + a.map(x => typeof x === "number" && (x as number) > 0xffff ? hex(x as number) : String(x)).join(", ") : ""), target: target_ });\n`;
code += `  switch (name) {\n`;
for (const t of table) {
  const args = formats[t.name] ?? fallback[t.name];
  if (!args) { missing.push(t.name); continue; }
  code += `  case "${t.name}": return fmt(${args});\n`;
}
code += `  default: return { name, text: name.toLowerCase() + " ?" + hex(raw) };\n  }\n}\n`;
writeFileSync(out, code);
console.log(`${table.length} opcodes, ${Object.keys(formats).length} inline formats; unformatted: ${missing.join(" ") || "none"}`);
